// Generates src/components/ui/icon-paths.ts from Material Symbols Outlined (weight 400).
import fs from "node:fs";
const names = ["menu","close","person","shopping_bag","arrow_forward","arrow_back","chevron_left","chevron_right","location_on","layers","edit_note","photo_camera","handyman","search","tune","delete","add","remove","info","error","check_circle","warning","visibility","visibility_off","mail","lock","receipt_long","badge","logout","zoom_in","upload","image","inventory_2","keyboard_arrow_down","refresh","wifi_off","check","content_cut","straighten","palette","calendar_month","payments","home","grid_view","package_2"];
const dir = "node_modules/@material-symbols/svg-400/outlined/";
let out = "/* Generated by scripts/build-icons.mjs from @material-symbols/svg-400 (outlined). Do not edit. */\nexport const ICON_PATHS = {\n";
for (const n of names) {
  const svg = fs.readFileSync(dir + n + ".svg", "utf8");
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map(m => m[1]).join(" ");
  out += `  ${JSON.stringify(n)}: ${JSON.stringify(d)},\n`;
}
out += "} as const;\nexport type IconName = keyof typeof ICON_PATHS;\n";
fs.writeFileSync("src/components/ui/icon-paths.ts", out);
console.log("icons", names.length);
